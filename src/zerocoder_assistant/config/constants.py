# ---------------------------------------------------------------------------
# Признаки отказа в ответе модели (этап 7)
# ---------------------------------------------------------------------------

#: Отказ опознаётся по СОВПАДЕНИЮ ДВУХ признаков в одном предложении: слова о
#: границах базы знаний и отрицания.
#:
#: Первая версия искала просто «в конспектах» — и была нефальсифицируемой.
#: Системный промпт сам велит модели употреблять этот оборот в ветке B («как
#: задать размер чанка — в конспектах есть [1]»), поэтому уверенно выдуманный
#: ответ, сформулированный грамотно, засчитывался как отказ. Метрика обещала
#: оценку снизу, а давала оценку сверху — то есть измеряла ровно наоборот.
#:
#: Признак всё равно приблизительный: он ловит формулировку, а не смысл. Судить
#: моделью было бы точнее, но тогда метрика качества зависела бы от модели,
#: которую ею же и меряют.
#: Все списки ниже — НАЧАЛА слов, и сопоставляются они с начала слова. Поиск
#: подстрокой без границ давал ложные срабатывания на ровном месте: «личный
#: каби-НЕТ» и «ин-ТЕРНЕТ-магазин» содержат «нет», а «МАТЕРИАЛ урока объясняет»
#: — слово о границах базы. Пара таких совпадений в одном предложении
#: превращала уверенную выдумку в засчитанный отказ.
