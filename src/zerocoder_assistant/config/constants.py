#: Слова, по которым вопрос узнаётся как продолжение предыдущего.
#:
#: Нужны не генерации, а ПОИСКУ. Модель поймёт «а сколько его ставить?» из
#: истории диалога, но эмбеддинг этой фразы сам по себе не найдёт в базе ничего
#: про overlap: в тексте вопроса нет ни одного предметного слова. Поэтому в
#: поисковый запрос подмешивается предыдущий вопрос пользователя — но только
#: когда текущий без него не стоит.
#:
#: Признак заведомо приблизительный: «что такое overlap и зачем он нужен?» тоже
#: содержит «он» и тоже потянет за собой предыдущий вопрос. Цена ошибки
#: несимметрична — лишний контекст в поисковом запросе слегка размывает выдачу,
#: а пропущенное уточнение даёт отказ на осмысленный вопрос. Расширять запрос
#: через отдельный вызов модели сознательно не стали: это лишний запрос на
