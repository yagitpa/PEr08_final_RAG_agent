"""
Распознавание уточняющего вопроса.

Проблема касается только поиска. Модель поймёт «а сколько его ставить?» из
истории диалога — история едет в запрос целиком. А вот эмбеддинг этой фразы не
найдёт в базе ничего про overlap: в вопросе нет ни одного предметного слова,
всё содержание осталось в предыдущей реплике.

Поэтому поисковый запрос собирается из предыдущего вопроса и текущего. Не из
всей истории: чем больше чужого текста в запросе, тем сильнее размывается
вектор и тем дальше выдача уезжает от того, что спросили сейчас.
"""

from __future__ import annotations

from zerocoder_assistant.config.constants import (
    FOLLOW_UP_MARKERS,
    FOLLOW_UP_MAX_WORDS,
    FOLLOW_UP_MIN_STANDALONE_WORDS,
    FOLLOW_UP_OPENERS,
    WORD_PATTERN,
)


def words(text: str) -> list[str]:
    """Слова вопроса в нижнем регистре."""
    return WORD_PATTERN.findall(text.lower())


def is_follow_up(question: str, *, max_words: int = FOLLOW_UP_MAX_WORDS) -> bool:
    """Похож ли вопрос на продолжение предыдущего.

    Признака два, и нужны оба. Первый — отсылка наружу: союз-связка в начале
    реплики или местоимение в любом месте. Второй — краткость: длинный вопрос
    несёт достаточно предметных слов, чтобы найтись самому, даже если начат с
    «а» и содержит «он».

    Одного первого признака мало. «Что такое overlap и зачем он нужен?» —
    самодостаточный вопрос, и подмешивать в него предыдущую реплику значит
    уводить поиск от того, что спросили сейчас.

    Совсем короткий вопрос — исключение из правила «нужны оба признака».
    В «Зачем?» отсылке негде стоять, но и предметного слова в нём нет ни
    одного: искать по такому тексту нечего, и без предыдущей реплики он
    гарантированно даст отказ.
    """
    tokens = words(question)
    if not tokens or len(tokens) > max_words:
        return False
    if len(tokens) < FOLLOW_UP_MIN_STANDALONE_WORDS:
        return True
    return tokens[0] in FOLLOW_UP_OPENERS or bool(FOLLOW_UP_MARKERS.intersection(tokens))
