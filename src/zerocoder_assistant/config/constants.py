#: «почему» и «зачем» из списка убраны. Это обычные вопросительные слова, а не
#: отсылки к сказанному: «Почему модель галлюцинирует?» и «Зачем нужен порог
#: релевантности?» самодостаточны, но опознавались уточнениями и тянули в
#: поисковый запрос предыдущую реплику. Настоящее уточнение с этими словами
#: короче трёх слов («Зачем?») либо начинается с союза («а почему?») — и то,
#: и другое ловится без них.

#: Вопрос короче трёх слов не несёт содержания вовсе и найтись сам по себе не
#: может: «Зачем?», «Почему?», «Подробнее?». Такой всегда продолжение —
#: отдельного признака отсылки для него не требуется.
FOLLOW_UP_MIN_STANDALONE_WORDS: Final[int] = 3

#: Сколько слов допускает уточняющий вопрос. Второй признак, без которого
#: первый ловит лишнее: «что такое overlap и зачем он нужен?» содержит «он», но
#: предметных слов в нём хватает и без предыдущей реплики. Отсылка сама по себе
#: ничего не значит — значение имеет отсылка вместо содержания.
FOLLOW_UP_MAX_WORDS: Final[int] = 6

#: Союзы, с которых начинается реплика-продолжение: «а сколько?», «и что дальше?».
#: Проверяются только в начале вопроса — в середине предложения это обычные слова.
FOLLOW_UP_OPENERS: Final[tuple[str, ...]] = ("а", "и", "но", "ну", "ок", "окей", "хорошо")

