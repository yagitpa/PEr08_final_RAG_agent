ARROW_TRANSLATIONS: Final[dict[str, str]] = {
    "→": "->",
    "⟶": "->",
    "⇒": "->",
    "⇨": "->",
    "←": "<-",
    "⟵": "<-",
    "⇐": "<-",
    "↔": "<->",
    "⇔": "<->",
}

#: Диагональные стрелки, наоборот, чисто декоративные: ими размечены подзаголовки
#: («Почему модели выдумывают? ↘️»). Их удаляем.
DECORATIVE_ARROWS: Final[str] = "↘↗↙↖⬊⬈⬋⬉⤵⤴"

#: Эмодзи и пиктограммы. Конспекты обильно размечены ✅ 💡 ⚠️ ▶️ ✍️ ❓ —
#: для эмбеддинга это чистый шум.
#: Диапазоны заданы escape-последовательностями, а не литералами: половину этих
#: символов не видно в редакторе, и пропущенный блок обнаруживается только
#: постфактум. Так было с «▶» (U+25B6) — селектор начертания снимался, сам
#: треугольник оставался, и строка «▶ Время чтения» переставала опознаваться
#: как административная.
#:
#: Диапазон стрелок (U+2190-U+21FF) сюда намеренно НЕ входит: он захватывал «→».
#: Из него удаляются только перечисленные выше декоративные диагонали.
EMOJI_PATTERN: Final[re.Pattern[str]] = re.compile(
    "[" + DECORATIVE_ARROWS + "\U0001f000-\U0001f2ff"  # плитки, карты, закрытые буквы
    "\U0001f300-\U0001faff"  # символы, пиктограммы, эмодзи
    "⌀-⏿"  # технические (⏱ ⌛ ⏰)
    "■-◿"  # геометрические фигуры (▶ ◀ ■ ●)
    "☀-➿"  # разное и дингбаты (✅ ✍ ❓ ⚠)
    "⬀-⯿"  # стрелки-пиктограммы
    "™ℹ"  # ™ ℹ
    "︎️"  # селекторы начертания
    "⃣"  # клавишная рамка
    "]+",
    flags=re.UNICODE,
)

