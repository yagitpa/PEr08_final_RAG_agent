"""
Контракт поставщика эмбеддингов.

Протокол, а не абстрактный класс: тесты подсовывают сюда простую заглушку без
наследования и без сети, а добавление Сбера или Яндекса не требует правок ядра.

Ключевое свойство, ради которого этот слой вообще выделен: **эмбеддинги
непереносимы между моделями**. Векторы разных моделей лежат в разных
пространствах, и поиск по чужому индексу не падает, а тихо возвращает мусор.
Поэтому `model_id` и `dimension` — часть контракта: они уходят в манифест
индекса, и при следующем запуске система сверяет их и отказывается работать
с несовместимым индексом.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol, runtime_checkable


@runtime_checkable
class EmbeddingProvider(Protocol):
    """Превращает тексты в векторы."""

    @property
    def model_id(self) -> str:
        """Имя модели, попадающее в манифест индекса."""

    @property
    def dimension(self) -> int:
        """Размерность вектора."""

    def embed(self, texts: Sequence[str]) -> list[list[float]]:
        """Векторы для набора текстов, в том же порядке.

        Реализация сама разбивает набор на батчи: вызывающий код не должен
        знать про ограничения конкретного API.
        """

