#: Именно HTML-тег, а не «что угодно между < и >». Широкий вариант
#: (`<[^>\n]{1,200}>`) молча съедал осмысленный текст технического корпуса:
#: «<1 - допускает повторы; >» из таблицы параметров, плейсхолдеры
#: «ngrok http <нужный-порт>», инструкцию «нажимаем на кнопку `</>`».
#: Имя тега обязано начинаться с латинской буквы — этого достаточно, чтобы
#: отличить разметку от сравнений и кириллических плейсхолдеров.
HTML_TAG_PATTERN: Final[re.Pattern[str]] = re.compile(
    r"</?[A-Za-z][A-Za-z0-9-]*(?:\s[^<>\n]{0,200})?/?>|<!--.*?-->",
    flags=re.DOTALL,
)

#: ![alt](url) -> alt, [текст](url) -> текст.
