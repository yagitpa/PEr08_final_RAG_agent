"""
Дедупликация результатов поиска.

Что она делает и чего не делает — по замерам на реальном корпусе, а не по
ожиданиям. Прогон golden set (51 вопрос, 5355 пар кандидатов в одной выдаче)
даёт такое распределение сходства по шинглам:

    J ~ 0.0 : 5243 пары
    J ~ 0.1 :   98
    J ~ 0.2 :   14      <- максимум по корпусу 0.200

**Перекрытие чанков дедупликацию не запускает и не должно.** Соседние чанки
одной секции — те самые 15% overlap — дают медиану 0.089 и максимум 0.188 (74
пары). Это ровно то, что предсказывает арифметика: доля общих шинглов при
перекрытии p равна p/(2-p), для 15% — около 0.081. Выбросить один из двух
соседних чанков значит потерять те 85% текста, которыми они различаются, —
поэтому порог стоит НАМНОГО выше этих значений.

Отсюда роль механизма: он ловит **дословный повтор**, а не перекрытие. Секция,
скопированная из урока в урок, две редакции одного абзаца, чанк, попавший в
выдачу дважды. На нынешнем корпусе такого нет — при пороге 0.8 дедупликация не
срабатывает ни разу, и это правильный результат, а не мёртвый код: цена
проверки — доли миллисекунды на запрос, а цена её отсутствия в тот день, когда
конспекты начнут повторяться, — половина контекста в повторах.

Сравнение идёт по шинглам, а не по множеству слов. Два фрагмента об одном и том
же предмете имеют почти одинаковый словарь, но разный порядок слов; дословный
повтор копирует текст подряд. Шинглы ловят именно дословность.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from typing import Protocol, TypeVar

#: Длина шингла в словах. Пять — компромисс: короче начинает срабатывать на
#: устойчивых оборотах вроде «в этом случае мы можем», длиннее перестаёт видеть
#: повтор длиной в одно предложение.
SHINGLE_SIZE = 5

_WORD = re.compile(r"\w+", flags=re.UNICODE)


class _Comparable(Protocol):
    """Минимум, который нужен дедупликации от результата поиска."""

    chunk_id: str
    text: str
    similarity: float


#: Синтаксис дженериков PEP 695 (`def f[T](...)`) появился в 3.12, а проект
#: объявлен совместимым с 3.11 — поэтому обычный TypeVar.
_Hit = TypeVar("_Hit", bound=_Comparable)


def shingles(text: str, size: int = SHINGLE_SIZE) -> set[tuple[str, ...]]:
    """Множество последовательностей из `size` слов подряд."""
    words = [word.casefold() for word in _WORD.findall(text)]
    if len(words) < size:
        return {tuple(words)} if words else set()
    return {tuple(words[i : i + size]) for i in range(len(words) - size + 1)}


def jaccard(left: set[tuple[str, ...]], right: set[tuple[str, ...]]) -> float:
    """Доля общих шинглов: 1.0 — тексты дословно совпадают, 0.0 — ничего общего."""
    if not left or not right:
        return 0.0
    intersection = len(left & right)
    return intersection / (len(left) + len(right) - intersection)


def deduplicate(hits: Sequence[_Hit], threshold: float) -> tuple[list[_Hit], int]:
    """Оставляет по одному фрагменту из каждой группы похожих.

    Порядок входа считается порядком убывания релевантности, поэтому из пары
    похожих остаётся тот, что найден раньше — то есть более релевантный.

    Порог обязан быть строго больше нуля. При нулевом пороге условие
    `jaccard >= 0` истинно для любой пары, включая пары без единого общего
    слова, и от выдачи остаётся ровно один фрагмент. Настройки такого значения
    не допускают (`DEDUP_THRESHOLD` объявлен `gt=0`), но функция публичная.

    Возвращает отобранные фрагменты и число отброшенных.
    """
    if threshold <= 0:
        raise ValueError(
            f"Порог дедупликации должен быть больше нуля, получено {threshold}: "
            "при нуле похожими считаются любые два фрагмента и в выдаче остаётся один."
        )

    kept: list[_Hit] = []
    kept_shingles: list[set[tuple[str, ...]]] = []
    seen_texts: set[str] = set()
    removed = 0

    for hit in hits:
        # Точный дубль отсекается дёшево, без разбора на шинглы.
        normalized = " ".join(_WORD.findall(hit.text.casefold()))
        if normalized in seen_texts:
            removed += 1
            continue

        current = shingles(hit.text)
        if any(jaccard(current, previous) >= threshold for previous in kept_shingles):
            removed += 1
            continue

        kept.append(hit)
        kept_shingles.append(current)
        seen_texts.add(normalized)

    return kept, removed
