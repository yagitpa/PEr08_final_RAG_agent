#: Инлайн-код изымается ДО снятия выделения и возвращается после.
#: Иначе `*args`, `**kwargs`, `__pycache__` внутри обратных кавычек сначала
#: лишаются кавычек, а следующим проходом теряют звёздочки и подчёркивания.
MD_INLINE_CODE_PATTERN: Final[re.Pattern[str]] = re.compile(r"`([^`\n]+)`")

#: Маркеры выделения снимаются, содержимое остаётся.
#: `(?=\S)` не даёт схлопнуть арифметику вида «top_k * 3».
#: Без DOTALL намеренно: иначе одиночная звёздочка в одной строке спарилась бы
#: с другой через полстраницы и вырезала бы всё между ними.
#:
#: Двойного подчёркивания здесь нет сознательно. В корпусе все 52 вхождения
#: `__...__` — это Python-дандеры (`__init__`, `__name__`, `__main__`,
#: `__pycache__`, `__future__`), и ни одного случая разметки. Обрабатывать их
#: как выделение значит превращать «файл __init__.py» в «файл init.py» — то есть
#: терять термин, по которому студент и будет искать.
MD_EMPHASIS_PATTERN: Final[re.Pattern[str]] = re.compile(r"(\*{1,3})(?=\S)(.+?)(?<=\S)\1")

#: Сколько раз прогоняется снятие выделения: вложенные конструкции снимаются послойно.
